        // 12. CREATE: guardar un producto
    private void guardarProducto() {
        // Valida que los campos no estén vacíos
        if (!validarCampos()) {
            return;
        }

        // Valida el formato numérico del precio
        Double precio = obtenerPrecioValido();
        if (precio == null) {
            return;
        }

        // Valida el formato numérico del stock
        Integer stock = obtenerStockValido();
        if (stock == null) {
            return;
        }

        // Obtener los datos del formulario
        String nombre = txtNombre.getText().trim();
        String categoria = cboCategoria.getSelectedItem().toString();
        int idCategoria = categorias.get(categoria); // Recupera el ID correspondiente usando el Map

        String sql = "INSERT INTO producto (nombre, id_categoria, precio, stock) VALUES (?, ?, ?, ?)";

        try (Connection cn = Conexion.conectar();
             PreparedStatement ps = cn.prepareStatement(sql)) {

            // Asignación de parámetros (?) en orden
            ps.setString(1, nombre);
            ps.setInt(2, idCategoria);
            ps.setDouble(3, precio);
            ps.setInt(4, stock);

            // Ejecuta la inserción en la base de datos
            ps.executeUpdate();

            JOptionPane.showMessageDialog(this, "Producto registrado correctamente");

            // Refresca la interfaz
            listarProductos();
            limpiar();
            estadoInicial();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al registrar: " + e.getMessage());
        }
    }
    // 13. Seleccionar un registro del JTable
    private void cargarRegistroSeleccionado() {
        int fila = tblProductos.getSelectedRow();
        
        // Verifica que realmente se haya seleccionado una fila válida
        if (fila >= 0) {
            // Jala los datos de las columnas de la fila seleccionada y los pone en los campos
            txtId.setText(tblProductos.getValueAt(fila, 0).toString());
            txtNombre.setText(tblProductos.getValueAt(fila, 1).toString());
            cboCategoria.setSelectedItem(tblProductos.getValueAt(fila, 2).toString());
            txtPrecio.setText(tblProductos.getValueAt(fila, 3).toString());
            txtStock.setText(tblProductos.getValueAt(fila, 4).toString());
            
            // Cambia la botonera al estado de edición (Sección 6.4)
            estadoEdicion();
        }
    }
