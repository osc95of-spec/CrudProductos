    private void cargarCategorias() {
        cboCategoria.removeAllItems();
        categorias.clear();
        
        String sql = "SELECT id_categoria, nombre FROM categoria ORDER BY nombre";
        
        try (Connection cn = Conexion.conectar();
             PreparedStatement ps = cn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {
            
            while (rs.next()) {
                int id = rs.getInt("id_categoria");
                String nombre = rs.getString("nombre");
                
                cboCategoria.addItem(nombre);
                categorias.put(nombre, id); // Guarda la relación en el Map
            }
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al cargar categorías: " + e.getMessage());
        }
    }
    
        private void listarProductos() {
        DefaultTableModel modelo = new DefaultTableModel(
            new Object[]{"ID", "Producto", "Categoría", "Precio", "Stock"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // Bloquea la edición directa en la tabla (Sección 9 - Buenas prácticas)
            }
        };

        String sql = "SELECT p.id_producto, p.nombre, c.nombre AS categoria, p.precio, p.stock " +
                     "FROM producto p " +
                     "INNER JOIN categoria c ON p.id_categoria = c.id_categoria " +
                     "ORDER BY p.id_producto";

        try (Connection cn = Conexion.conectar();
             PreparedStatement ps = cn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {
                Object[] fila = {
                    rs.getInt("id_producto"),
                    rs.getString("nombre"),
                    rs.getString("categoria"),
                    rs.getDouble("precio"),
                    rs.getInt("stock")
                };
                modelo.addRow(fila);
            }
            tblProductos.setModel(modelo);

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al listar productos: " + e.getMessage());
        }
    }
    // 10.1 Validar campos obligatorios
    private boolean validarCampos() {
        if (txtNombre.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el nombre del producto");
            txtNombre.requestFocus();
            return false;
        }
        if (cboCategoria.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Seleccione una categoría");
            return false;
        }
        if (txtPrecio.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el precio");
            txtPrecio.requestFocus();
            return false;
        }
        if (txtStock.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el stock");
            txtStock.requestFocus();
            return false;
        }
        return true;
    }

    // 10.2 Obtener un precio válido
    private Double obtenerPrecioValido() {
        try {
            double precio = Double.parseDouble(txtPrecio.getText().trim());
            if (precio <= 0) {
                JOptionPane.showMessageDialog(this, "El precio debe ser mayor que cero");
                txtPrecio.requestFocus();
                return null;
            }
            return precio;
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese un precio válido");
            txtPrecio.requestFocus();
            return null;
        }
    }

    // 10.3 Obtener un stock válido
    private Integer obtenerStockValido() {
        try {
            int stock = Integer.parseInt(txtStock.getText().trim());
            if (stock < 0) {
                JOptionPane.showMessageDialog(this, "El stock no puede ser negativo");
                txtStock.requestFocus();
                return null;
            }
            return stock;
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese un stock válido");
            txtStock.requestFocus();
            return null;
        }
    }
